#!/bin/bash
# Collect one MI dataset per sensing-configuration checkpoint.
#
#   scripts/collect_mi_checkpoints.sh [vision|vistac|tacff ...]
#
# Env knobs:
#   NUM_EPISODES   episodes per checkpoint            (default 2000)
#   NUM_ENVS       episodes per batch                 (default 50)
#   MAX_STEPS      first-success search horizon       (default 500)
#   TAIL_STEPS     steps kept after the first success (default 20)
#   START_SEED     first batch seed                   (default 300000)
#   OUT_ROOT       dataset directory                  (default data/mi_data)
#   SUFFIX         appended to each dataset name      (default "")
#   GPUS           GPU per checkpoint, space separated (default "0 1 0")
#   PILOT          1 -> pilot mode (report + censoring table)
#   EXTRA          extra flags passed straight to collect_mi.py
#   SUITE          pih (default) | objsearch -- picks checkpoints, task spec, names
#   PUBLISH        1 -> as soon as a run finishes, validate it and publish it to
#                  Manifold with publish_mi_datasets.sh (not after all runs)
#   DRY_RUN        1 -> print each run's command and exit
#
# Runs the requested checkpoints CONCURRENTLY, one per GPU, and tees each log
# next to its dataset. Two concurrent sims fit on 2x A100 80GB; three do not
# get their own GPU, so the default GPUS list doubles up only if you ask for
# all three at once.

set -euo pipefail

WORKSPACE="${WORKSPACE:-/data/users/meih/manifeel-workspace}"
REPO_ROOT="${REPO_ROOT:-$WORKSPACE/manifeel}"
MINIFORGE_HOME="${MINIFORGE_HOME:-$WORKSPACE/miniforge3}"
CONDA_ENV="${CONDA_ENV:-$MINIFORGE_HOME/envs/manifeel}"

NUM_EPISODES="${NUM_EPISODES:-2000}"
NUM_ENVS="${NUM_ENVS:-50}"
MAX_STEPS="${MAX_STEPS:-500}"
TAIL_STEPS="${TAIL_STEPS:-20}"
START_SEED="${START_SEED:-300000}"
OUT_ROOT="${OUT_ROOT:-data/mi_data}"
SUFFIX="${SUFFIX:-}"
PILOT="${PILOT:-0}"
EXTRA="${EXTRA:-}"

SUITE="${SUITE:-pih}"
PUBLISH="${PUBLISH:-0}"
DRY_RUN="${DRY_RUN:-0}"
case "$SUITE" in
  pih)
    TASK_ARGS=()
    declare -A CKPT=(
      [vision]="data/outputs/vision_pih_50/44/checkpoints/latest_epoch50.ckpt"
      [vistac]="data/outputs/vistac_pih_50/44/checkpoints/latest_epoch50.ckpt"
      [tacff]="data/outputs/tacff_pih_50/44/checkpoints/latest_epoch50.ckpt"
    )
    ;;
  objsearch)
    TASK_ARGS=(--task-spec object_search)
    # The best epoch per run on held-out seed 200000 (fetched by fbsource
    # scripts/fetch_manifeel_objsearch_policies.sh).
    declare -A CKPT=(
      [vision]="data/outputs/vision_objsearch_50/44/checkpoints/latest_epoch150.ckpt"
      [vistac]="data/outputs/vistac_objsearch_50/44/checkpoints/latest_epoch100.ckpt"
      [tacff]="data/outputs/tacff_objsearch_50/44/checkpoints/latest_epoch150.ckpt"
    )
    ;;
  *) echo "unknown SUITE '$SUITE' (want: pih objsearch)"; exit 1;;
esac

RUNS=("$@")
[ ${#RUNS[@]} -eq 0 ] && RUNS=(vision vistac tacff)
read -r -a GPU_LIST <<< "${GPUS:-0 1 0}"

# Collect, then (PUBLISH=1) validate and publish -- per run, so a finished dataset
# reaches Manifold while the others are still collecting.
collect_one() {
  local name="$1" gpu="$2" out="$3" log="$4"; shift 4
  MANIFEEL_GPU="$gpu" python collect_mi.py "$@" > "$log" 2>&1 || return 1
  [ "$PUBLISH" = "1" ] || return 0
  python -m mi_collection.validate_dataset --expect-episodes="$NUM_EPISODES" "$out" \
    >> "$log" 2>&1 || { echo "[$name] validation failed; not publishing" >> "$log"; return 1; }
  scripts/publish_mi_datasets.sh "$out" >> "$log" 2>&1
}

# shellcheck disable=SC1091  # generated by the Miniforge install, not in-repo
source "$MINIFORGE_HOME/etc/profile.d/conda.sh"
conda activate "$CONDA_ENV"
export LD_LIBRARY_PATH="${CONDA_PREFIX}/lib:${LD_LIBRARY_PATH:-}"
export WANDB_MODE="${WANDB_MODE:-offline}"
cd "$REPO_ROOT"

pids=()
for i in "${!RUNS[@]}"; do
  name="${RUNS[$i]}"
  ckpt="${CKPT[$name]:-}"
  [ -n "$ckpt" ] || { echo "unknown run '$name'; have ${!CKPT[*]}"; exit 1; }
  [ -f "$ckpt" ] || [ "$DRY_RUN" = "1" ] || { echo "no such checkpoint: $ckpt"; exit 1; }
  gpu="${GPU_LIST[$((i % ${#GPU_LIST[@]}))]}"
  out="$OUT_ROOT/manifeel_${SUITE}_${name}_${NUM_EPISODES}${SUFFIX}.zarr"
  log="${out%.zarr}.log"
  mkdir -p "$(dirname "$out")"

  args=(--checkpoint "$ckpt" --out "$out" --device "cuda:$gpu"
        --num-episodes "$NUM_EPISODES" --num-envs "$NUM_ENVS"
        --max-steps "$MAX_STEPS" --success-tail-steps "$TAIL_STEPS"
        --start-seed "$START_SEED" --resume --overwrite "${TASK_ARGS[@]}")
  [ "$PILOT" = "1" ] && args+=(--pilot)
  # shellcheck disable=SC2206  # word splitting is the point for EXTRA
  [ -n "$EXTRA" ] && args+=($EXTRA)

  echo "[$name] gpu=$gpu out=$out log=$log"
  if [ "$DRY_RUN" = "1" ]; then
    echo "MANIFEEL_GPU=$gpu python collect_mi.py ${args[*]}"
    continue
  fi
  collect_one "$name" "$gpu" "$out" "$log" "${args[@]}" &
  pids+=($!)
done

status=0
for i in "${!pids[@]}"; do
  if ! wait "${pids[$i]}"; then
    echo "FAILED: ${RUNS[$i]} (see log)"
    status=1
  else
    echo "done: ${RUNS[$i]}"
  fi
done
exit "$status"
